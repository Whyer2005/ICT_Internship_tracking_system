/**
 * ค่าจากฟอร์ม/Excel -> ชื่อจังหวัดมาตรฐาน
 * ตัด "จังหวัด" / "จ." นำหน้า, รองรับชื่อย่อที่ใช้บ่อย (กทม, อยุธยา, โคราช)
 * คืน "" เมื่อว่าง และ null เมื่อไม่รู้จัก
 */
export function normalizeProvince(raw: unknown): string | null {
  const s = String(raw ?? "")
    .replace(/\s+/g, "")
    .replace(/^(จังหวัด|จ\.)/, "")
    .trim();
  if (!s) return "";
  if (s === PROVINCE_ABROAD) return PROVINCE_ABROAD;
  const found = THAI_PROVINCES.find((p) => p === s);
  if (found) return found;
  return ALIASES[s.toLowerCase()] || ALIASES[s] || null;
}

export function thaiProvincesDataScript(): string {
  return `<script type="application/json" id="thai-provinces-data">${JSON.stringify([...THAI_PROVINCES, PROVINCE_ABROAD])}</script>`;
}
